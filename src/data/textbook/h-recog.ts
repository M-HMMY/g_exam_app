周波数ごとの強さをグラフに描くと、細かい山が並んだ形になります。**その細かい山を無視して、全体のなだらかな輪郭だけを取り出したもの**を**スペクトル包絡**といいます。

そして、**スペクトル包絡に現れる山**を**フォルマント**、その山の位置（周波数）を**フォルマント周波数**といいます。

